#!/usr/bin/env node
/**
 * Sync concept projects from design/portfolio/<slug>/project.json into lib/field-projects.ts.
 *
 *   node design/sync-projects.cjs
 *
 * Reads each project.json and the rendered boards in public/portfolio/concepts/<slug>/,
 * measures every JPEG, and writes typed Project entries. Boards listed in project.json
 * but missing on disk are skipped with a warning.
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const SRC = path.join(__dirname, "portfolio");
const OUT = path.join(ROOT, "lib/field-projects.ts");
const VALID = new Set(["brand-identity", "web", "ai", "3d-motion", "marketing", "graphic"]);
// Display order of the generated projects.
const ORDER = ["corvane", "veyra", "orra", "selune", "motus", "lattice"];

/** Reads width/height from a baseline or progressive JPEG. */
function jpegSize(file) {
  const b = fs.readFileSync(file);
  let i = 2;
  while (i < b.length) {
    if (b[i] !== 0xff) {
      i++;
      continue;
    }
    const marker = b[i + 1];
    const len = b.readUInt16BE(i + 2);
    if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) {
      return { height: b.readUInt16BE(i + 5), width: b.readUInt16BE(i + 7) };
    }
    i += 2 + len;
  }
  throw new Error(`cannot read JPEG size: ${file}`);
}

const slugs = fs
  .readdirSync(SRC)
  .filter((d) => !d.startsWith("_") && fs.existsSync(path.join(SRC, d, "project.json")))
  .sort((a, b) => (ORDER.indexOf(a) + 1 || 99) - (ORDER.indexOf(b) + 1 || 99));

const q = (v) => JSON.stringify(v);
const entries = [];
for (const slug of slugs) {
  const p = JSON.parse(fs.readFileSync(path.join(SRC, slug, "project.json"), "utf8"));
  const cats = (p.categories || []).filter((c) => VALID.has(c));
  if (!cats.length) throw new Error(`${slug}: no valid categories`);
  const images = [];
  for (const b of p.boards || []) {
    const file = path.join(ROOT, "public/portfolio/concepts", slug, b.file);
    if (!fs.existsSync(file)) {
      console.warn(`! ${slug}: missing ${b.file} — skipped`);
      continue;
    }
    const { width, height } = jpegSize(file);
    images.push({ src: `/portfolio/concepts/${slug}/${b.file}`, alt: b.alt || `${p.title} — ${b.caption}`, width, height, caption: b.caption });
  }
  if (!images.length) throw new Error(`${slug}: no rendered boards`);
  const img = (x) => `img(${q(x.src)}, ${q(x.alt)}, ${x.width}, ${x.height}${x.caption ? `, ${q(x.caption)}` : ""})`;
  entries.push(`  {
    slug: ${q(p.slug || slug)},
    title: ${q(p.title)},
    discipline: ${q(p.discipline)},
    categories: ${q(cats)},
    kind: "concept",
    summary: ${q(p.summary)},
    overview: ${q(p.overview)},
    challenge: ${q(p.challenge)},
    solution: ${q(p.solution)},
    services: ${q(p.services || [])},${p.palette && p.palette.length ? `\n    palette: ${q(p.palette)},` : ""}
    cover: ${img(images[0])},
    gallery: [
${images.slice(1).map((x) => `      ${img(x)},`).join("\n")}
    ],
  }`);
  console.log(`✓ ${slug}: ${images.length} boards`);
}

fs.writeFileSync(
  OUT,
  `import type { Project, ProjectImage } from "./projects";

/**
 * FIELD PROJECTS — self-initiated concept projects, one per service field,
 * art-directed and rendered from code in design/portfolio/<slug>/.
 * Generated by \`node design/sync-projects.cjs\` — edit project.json, not this file.
 */
const img = (src: string, alt: string, width: number, height: number, caption?: string): ProjectImage => ({
  src,
  alt,
  width,
  height,
  caption,
});

export const fieldProjects: Project[] = [
${entries.join(",\n")}${entries.length ? "," : ""}
];
`,
);
console.log(`wrote ${path.relative(ROOT, OUT)} (${entries.length} projects)`);
