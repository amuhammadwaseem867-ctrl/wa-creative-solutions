import type { Project, ProjectImage } from "./projects";

/**
 * LIVE PROJECTS, deployed builds from the studio's repositories, best first.
 * Demos and proposals that are online but not client sites are kind "concept".
 * Screenshots are captured from each live site (1440×900 desktop screens, a
 * six-screen scroll capture and a 390×844 phone screen) and saved as WebP in
 * public/portfolio/live/<slug>/.
 */
const img = (src: string, alt: string, width: number, height: number, caption?: string): ProjectImage => ({
  src,
  alt,
  width,
  height,
  caption,
});

/** Cover, gallery, scroll capture and phone screen for one live site. */
function screens(slug: string, title: string, pages: string[], scrollHeight?: number) {
  const dir = `/portfolio/live/${slug}`;
  const desktop = pages.map((page, i) => img(`${dir}/desktop-${i}.webp`, `${title}, ${page.toLowerCase()} (desktop)`, 1920, 1200, `${page}, desktop`));
  const mobile = img(`${dir}/mobile-0.webp`, `${title}, ${pages[0].toLowerCase()} (mobile)`, 585, 1266, `${pages[0]}, mobile`);
  return {
    cover: desktop[0],
    gallery: [...desktop, mobile],
    mobile,
    scroll: scrollHeight ? img(`${dir}/long.webp`, `${title}, ${pages[0].toLowerCase()}, full scroll`, 1200, scrollHeight) : undefined,
  };
}

